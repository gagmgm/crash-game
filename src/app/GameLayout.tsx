import { lazy, Suspense } from 'react';
import { Balance } from '../components/Balance/Balance';
import { BetPanel } from '../components/BetPanel/BetPanel';
import { ConnectionOverlay } from '../components/ConnectionStatus/ConnectionOverlay';
import { ConnectionStatus } from '../components/ConnectionStatus/ConnectionStatus';
import { GameCanvas } from '../components/GameCanvas/GameCanvas';
import { History } from '../components/History/History';
import { MuteButton } from './MuteButton';
import { useGameSession } from './session';
import styles from './GameLayout.module.css';

// Development-only: the condition is statically false in production builds, so the
// DevPanel chunk is never emitted.
const DevPanel = import.meta.env.DEV ? lazy(() => import('../components/DevPanel/DevPanel')) : null;

export function GameLayout() {
  const { backend } = useGameSession();
  return (
    <div className={styles.shell}>
      <header className={styles.topBar}>
        <div className={styles.brand}>
          <span aria-hidden>🚀</span>
          <span className={styles.brandName}>CRASH</span>
          {backend === 'mock' && (
            <span
              className={styles.badge}
              title="Outcomes are generated by the in-browser mock server"
            >
              MOCK SERVER
            </span>
          )}
        </div>
        <div className={styles.history}>
          <History />
        </div>
        <div className={styles.right}>
          <Balance />
          <ConnectionStatus />
          <MuteButton className={styles.iconButton} />
        </div>
      </header>

      <main className={styles.stage}>
        <GameCanvas />
        <ConnectionOverlay />
      </main>

      <div className={styles.panel}>
        <BetPanel />
      </div>

      {DevPanel && (
        <Suspense fallback={null}>
          <DevPanel />
        </Suspense>
      )}
    </div>
  );
}
